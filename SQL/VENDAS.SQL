
SELECT 
       SUM(PCPEDI.QT) AS QT,
       SUM(ROUND(NVL(PCPEDI.QT,0)*(NVL(PCPEDI.PVENDA, 0) + NVL(PCPEDI.VLOUTRASDESP, 0) + NVL(PCPEDI.VLFRETE, 0)),2)) AS PVENDA,
       SUM(ROUND(NVL(PCPRODUT.PESOBRUTO,0)*NVL(PCPEDI.QT,0),2)) AS TOTPESO,
       COUNT(DISTINCT(PCPEDC.CODCLI)) AS QTCLIPOS,
       SUM(ROUND(NVL(PCPEDI.QT,0)*NVL(PCPEDI.VLCUSTOFIN,0),2)) AS VLCUSTOFIN,
  ((SUM(ROUND(NVL(PCPEDI.QT,0)*(NVL(PCPEDI.PVENDA, 0) + NVL(PCPEDI.VLOUTRASDESP, 0) + NVL(PCPEDI.VLFRETE, 0)),2))
  -  SUM(ROUND(NVL(PCPEDI.QT,0)*NVL(PCPEDI.VLCUSTOFIN,0),2))) /  decode(SUM(ROUND(NVL(PCPEDI.QT,0)*NVL(PCPEDI.PVENDA,0),2)),0,1,SUM(ROUND(NVL(PCPEDI.QT,0)*NVL(PCPEDI.PVENDA,0),2))) * 100 ) as clPERLUC
FROM     
PCPEDI,  
PCPEDC,  
PCPRODUT,
PCCLIENT,
PCFORNEC
WHERE 1=1 
AND PCPEDC.DATA BETWEEN 2026.08.17 00:00:00 AND 2026.08.17 00:00:00
AND PCPEDC.CODFILIAL IN ('1','2')
AND PCPEDC.CONDVENDA IN (1, 2, 3, 7, 9, 14, 15, 17, 18, 19, 98)
and PCPEDC.NUMPED    = PCPEDI.NUMPED
AND   PCPEDI.CODPROD   = PCPRODUT.CODPROD
AND   PCPEDC.CODCLI    = PCCLIENT.CODCLI
AND   PCPRODUT.CODFORNEC = PCFORNEC.CODFORNEC
 AND NVL(PCPEDI.BONIFIC, 'N') =  'N' 

  AND EXISTS ( SELECT 1
              /* SQL UTILIZADO PELA ROTINA PCSIS322 PARA TODOS RELATORIO(S) */ 
                FROM PCLIB 
                WHERE PCLIB.CODFUNC = 503.000000 
                AND PCLIB.CODTABELA = 7 
                AND PCLIB.CODIGON =  PCPEDC.CODSUPERVISOR 
              ) 
  AND (PCPRODUT.CODFORNEC IN 
              (/* SQL UTILIZADO PELA ROTINA PCSIS322 PARA TODOS RELATORIO(S) */ SELECT CODIGON 
                FROM PCLIB 
                WHERE CODFUNC = 503.000000 
                AND CODTABELA = 3) ) 
AND   PCPEDC.DTCANCEL IS NULL 