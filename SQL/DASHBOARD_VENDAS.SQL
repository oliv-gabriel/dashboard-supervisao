SELECT c.CODUSUR,
       p.CODFORNEC,
       COUNT(DISTINCT c.CODCLI) AS QTCLIPOS,
       SUM(ROUND(NVL(i.QT, 0) * (NVL(i.PVENDA, 0) + NVL(i.VLOUTRASDESP, 0) + NVL(i.VLFRETE, 0)), 2)) AS PVENDA
  FROM PCPEDC c
  JOIN PCPEDI i ON i.NUMPED = c.NUMPED
  JOIN PCUSUARI u ON u.CODUSUR = c.CODUSUR
  JOIN PCPRODUT p ON p.CODPROD = i.CODPROD
 WHERE c.DATA BETWEEN :DATAI AND :DATAF
   /* PERMISSOES */
   AND c.CODFILIAL IN (/* FILIAIS */)
   AND c.CONDVENDA IN (1, 2, 3, 7, 9, 14, 15, 17, 18, 19, 98)
   AND NVL(i.BONIFIC, 'N') = 'N'
   AND c.DTCANCEL IS NULL
   AND u.CODSUPERVISOR NOT IN ('9999')
 GROUP BY ROLLUP(c.CODUSUR, p.CODFORNEC)