SELECT SUM(NVL(PCMETA.VLVENDAPREV, 0)) AS VLMETA,
       SUM(NVL(PCMETA.QTPESOPREV, 0)) AS QTPESOMETA,
       SUM(NVL(PCMETA.QTVENDAPREV, 0)) AS QTMETA,
       SUM(NVL(PCMETA.CLIPOSPREV, 0)) AS CLIPOSMETA
  FROM PCMETA
 WHERE PCMETA.CODUSUR = :CODUSUR
   AND PCMETA.TIPOMETA = :TIPOMETA
   AND PCMETA.DATA BETWEEN TRUNC(:DATAI, 'MM') AND LAST_DAY(:DATAF)
   /* AND EXISTS (SELECT 1 FROM PCPRODUT
                WHERE PCPRODUT.CODPROD = PCMETA.CODIGO
   ) */
   AND PCMETA.CODFILIAL IN ('1','2')
