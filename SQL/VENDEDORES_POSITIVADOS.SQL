SELECT DISTINCT
       PCUSUARI.CODUSUR,
       PCUSUARI.NOME,
       PCUSUARI.CODSUPERVISOR,
       PCUSUARI.DTTERMINO
  FROM PCUSUARI 
 WHERE PCUSUARI.CODSUPERVISOR NOT IN ('9999')
   AND NVL(PCUSUARI.BLOQUEIO, 'N') = 'N'
   AND PCUSUARI.DTEXCLUSAO IS NULL
   AND (PCUSUARI.DTTERMINO IS NULL OR PCUSUARI.DTTERMINO > SYSDATE)
   AND EXISTS ( SELECT 1
              /* SQL UTILIZADO PELA ROTINA PCSIS322 PARA TODOS RELATORIO(S) */ 
                FROM PCLIB 
                WHERE PCLIB.CODFUNC = :CODFUNC 
                AND PCLIB.CODTABELA = 7 
                AND PCLIB.CODIGON = PCUSUARI.CODSUPERVISOR 
              ) 
