SELECT COUNT(DISTINCT(PCPEDC.CODCLI)) QTCLIPOS,
       SUM(ROUND(NVL(PCPEDI.QT,0) * (NVL(PCPEDI.PVENDA, 0) + NVL(PCPEDI.VLOUTRASDESP, 0) + NVL(PCPEDI.VLFRETE, 0)),2)) AS PVENDA,
       ROUND(SUM(NVL(PCPEDI.QT,0) * (NVL(PCPEDI.PVENDA, 0) + NVL(PCPEDI.VLOUTRASDESP, 0) + NVL(PCPEDI.VLFRETE, 0) - NVL(PCPEDI.ST,0))), 2)  AS PVENDA_SEMST, 
       SUM(ROUND(NVL(PCPRODUT.VOLUME,0) * NVL(PCPEDI.QT,0),2)) AS VOLUME,
       ROUND(SUM(NVL(PCPRODUT.LITRAGEM, 0) * NVL(PCPEDI.QT,0)) ,2) AS LITRAGEM,
       SUM(NVL(PCPEDI.QT,0) / DECODE(NVL(PCPRODUT.QTUNIT,0),0,1,NVL(PCPRODUT.QTUNIT,1))) AS TOTQTUNIT,
       SUM(NVL(PCPEDI.QT,0) / DECODE(NVL(PCPRODUT.QTUNITCX,0),0,1,NVL(PCPRODUT.QTUNITCX,1))) AS TOTQTUNITCX,
       SUM(PCPEDI.QT) AS QT,
       SUM(ROUND(NVL(PCPRODUT.PESOBRUTO,0) * NVL(PCPEDI.QT,0),2)) AS TOTPESO
  FROM PCPEDI, PCPEDC, PCUSUARI, PCPRODUT, PCFORNEC,
       PCDEPTO, PCCLIENT, PCATIVI, PCPRACA, PCSUPERV
 WHERE PCPEDI.NUMPED = PCPEDC.NUMPED
   AND PCUSUARI.CODSUPERVISOR NOT IN ('9999')
AND PCPEDC.DATA BETWEEN :DATAI AND :DATAF
AND PCPEDC.CODFILIAL IN ('1','2')
AND PCPEDC.CONDVENDA IN (1, 2, 3, 7, 9, 14, 15, 17, 18, 19, 98)
 AND NVL(PCPEDI.BONIFIC, 'N') =  'N' 

  AND EXISTS ( SELECT 1
              /* SQL UTILIZADO PELA ROTINA PCSIS322 PARA TODOS RELATORIO(S) */ 
                FROM PCLIB 
                WHERE PCLIB.CODFUNC = :CODFUNC 
                AND PCLIB.CODTABELA = 7 
                AND PCLIB.CODIGON =  PCPEDC.CODSUPERVISOR 
              ) 
  AND (PCPRODUT.CODFORNEC IN 
              (/* SQL UTILIZADO PELA ROTINA PCSIS322 PARA TODOS RELATORIO(S) */ SELECT CODIGON 
                FROM PCLIB 
                WHERE CODFUNC = :CODFUNC 
                AND CODTABELA = 3) ) 
   AND PCPEDC.CODCLI = PCCLIENT.CODCLI
   AND PCCLIENT.CODATV1 = PCATIVI.CODATIV(+)
   AND PCPEDC.DTCANCEL IS NULL
   AND  PCPEDC.CODUSUR  = PCUSUARI.CODUSUR 
   AND PCPEDI.CODPROD = PCPRODUT.CODPROD
   AND PCPRODUT.CODEPTO = PCDEPTO.CODEPTO(+)
   AND PCPRODUT.CODFORNEC = PCFORNEC.CODFORNEC(+)
   AND PCPEDC.CODPRACA = PCPRACA.CODPRACA(+)
   AND PCUSUARI.CODSUPERVISOR = PCSUPERV.CODSUPERVISOR(+)
   AND  PCPEDC.CODUSUR  = :CODUSUR
 GROUP BY PCPEDC.CODUSUR, PCUSUARI.NOME
